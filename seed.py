"""Populate the database with realistic demo data:  python seed.py"""
import random
from datetime import datetime, timedelta
from db import connect, init_schema, ROOT
import os, workflow as wf

random.seed(42)
DB = os.environ.get("BIZTRACK_DB", os.path.join(ROOT, "instance", "biztrack.db"))
os.makedirs(os.path.dirname(DB), exist_ok=True)
conn = connect(DB); init_schema(conn)

TITLES = {
    "IT Support": ["VPN access issue", "New laptop setup", "Software licence renewal", "Email migration"],
    "Finance": ["Vendor invoice approval", "Expense reimbursement", "Budget revision", "Quarterly audit prep"],
    "HR": ["Onboarding new joiner", "Leave policy query", "Payroll correction", "Training enrolment"],
    "Procurement": ["Office supplies order", "Vendor onboarding", "Contract renewal", "Hardware quotation"],
    "Facilities": ["AC maintenance", "Meeting room booking", "Access card issue", "Desk relocation"],
    "Operations": ["Process change request", "Shipment delay review", "SOP update", "Inventory reconciliation"],
}
DEPTS = ["Sales", "Engineering", "Marketing", "Finance", "HR", "Operations"]
PEOPLE = ["Anita Rao", "Vikram Shah", "Priya Nair", "Karthik Reddy", "Sneha Iyer", "Rahul Verma", "Meera Das"]
STAFF = ["Arjun", "Divya", "Imran", "Lakshmi", "Suresh", "Tara"]
f = lambda d: d.isoformat(sep=" ", timespec="seconds")

now = datetime.now()
for i in range(70):
    cat = random.choice(list(TITLES))
    created = now - timedelta(days=random.randint(1, 160), hours=random.randint(0, 20))
    due = created + timedelta(days=random.choice([3, 5, 7, 10, 14]))
    pr = random.choices(wf.PRIORITIES, [2, 5, 3, 1])[0]
    cur = conn.execute(
        "INSERT INTO requests(title, description, category, priority, status, requester, department, "
        "created_at, due_date, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)",
        (f"{random.choice(TITLES[cat])} #{i+1}", "Demo request generated by seed.py.", cat, pr, "New",
         random.choice(PEOPLE), random.choice(DEPTS), f(created), due.date().isoformat(), f(created)))
    rid = cur.lastrowid
    roll = random.random()
    final = "Completed" if roll < .55 else "In Progress" if roll < .75 else "New" if roll < .87 else "On Hold" if roll < .95 else "Cancelled"
    ntasks = 0 if final in ("New", "Cancelled") else random.randint(2, 4)
    for t in range(ntasks):
        done = final == "Completed" or (final == "In Progress" and random.random() < .4)
        st = "Done" if done else random.choice(["To Do", "In Progress"])
        tc = created + timedelta(hours=random.randint(1, 24))
        comp = created + timedelta(days=random.uniform(.5, 12)) if st == "Done" else None
        conn.execute("INSERT INTO tasks(request_id, title, assignee, status, due_date, created_at, completed_at) "
                     "VALUES (?,?,?,?,?,?,?)",
                     (rid, f"Step {t+1}: " + random.choice(["Review", "Approve", "Execute", "Verify", "Notify"]),
                      random.choice(STAFF), st, due.date().isoformat(), f(tc), f(comp) if comp else None))
    closed = None
    if final in ("Completed", "Cancelled"):
        closed = created + timedelta(days=random.uniform(1, 16))
        closed = min(closed, now)
    conn.execute("UPDATE requests SET status=?, closed_at=?, updated_at=? WHERE id=?",
                 (final, f(closed) if closed else None, f(closed or created), rid))
    wf.log(conn, "request", rid, None, "New", "seeded")
    if final != "New":
        wf.log(conn, "request", rid, "New", final, "seeded")
conn.commit(); conn.close()
print(f"Seeded 70 requests into {DB}")
